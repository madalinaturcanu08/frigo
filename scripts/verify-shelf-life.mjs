// Checks Frigo's shelf-life table against USDA FoodKeeper and writes the verified values with exact citations.
// Rule: for each category + storage place, take the most common products of that kind in a Moldovan fridge, look up
// their official FoodKeeper times, and use the SHORTEST minimum (the safest choice; the user can always change a date).
// Input: content/foodkeeper-extract.json (official data, see its _source). Output: supabase/shelf-life-verified.sql
// (paste into the Supabase SQL editor to update the live database), the same rows inside supabase/seed.sql, and
// docs/SHELF_LIFE.md. Usage: npm run verify:shelf-life

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const fk = JSON.parse(fs.readFileSync(path.join(root, 'content/foodkeeper-extract.json'), 'utf8'));
const byId = new Map(fk.products.map((p) => [p.ID, p]));
const DAYS = { Days: 1, Weeks: 7, Months: 30, Years: 365 };

// [category, storage, old value, FoodKeeper product IDs]. A row without IDs has no FoodKeeper value (explained).
const ROWS = [
  ['dairy', 'fridge', 7, [33, 25, 2, 543]],
  ['dairy', 'freezer', 90, [27, 2, 1]],
  ['cheese', 'fridge', 14, [7, 9, 10, 546, 3]],
  ['cheese', 'freezer', 180, [7, 3, 5]],
  ['eggs', 'fridge', 28, [21]],
  ['eggs', 'pantry', 14, [], 'FoodKeeper (US) only gives refrigerated times for eggs. In Moldova eggs are sold unrefrigerated; 14 days is a Frigo default, below the 28-day best-before used in the EU.'],
  ['meat', 'fridge', 2, [43, 73, 113, 117, 102]],
  ['meat', 'freezer', 120, [43, 73, 117, 102]],
  ['fish', 'fridge', 2, [144, 146]],
  ['fish', 'freezer', 180, [144, 146]],
  ['vegetables', 'fridge', 7, [283, 296, 278, 279, 291, 600]],
  ['vegetables', 'freezer', 240, [279, 278, 296, 294, 297]],
  ['vegetables', 'pantry', 14, [297, 294, 600]],
  ['fruit', 'fridge', 7, [248, 251, 252, 481]],
  ['fruit', 'freezer', 240, [252, 481, 251]],
  ['fruit', 'pantry', 4, [], 'FoodKeeper gives no pantry time for fresh fruit (only "when ripe"); 4 days is a Frigo default.'],
  ['bread', 'fridge', 7, [195]],
  ['bread', 'freezer', 90, [195, 461]],
  ['bread', 'pantry', 4, [461, 574, 195]],
  ['leftovers', 'fridge', 3, [173, 174]],
  ['leftovers', 'freezer', 90, [173, 174]],
  ['sauces', 'fridge', 30, [348, 350, 351, 347, 353, 373]],
  ['sauces', 'pantry', 180, [350, 347, 351, 353, 373]],
  ['drinks', 'fridge', 7, [404, 455]],
  ['drinks', 'pantry', 180, [373]],
  ['other', 'fridge', 5, [], 'Too varied for one FoodKeeper product; Frigo default.'],
  ['other', 'freezer', 60, [], 'Too varied for one FoodKeeper product; Frigo default.'],
  ['other', 'pantry', 30, [], 'Too varied for one FoodKeeper product; Frigo default.'],
];

// Which FoodKeeper columns count for each storage place (date of purchase first, then general, then after opening).
const COLUMNS = {
  fridge: ['DOP_Refrigerate', 'Refrigerate', 'Refrigerate_After_Opening'],
  freezer: ['DOP_Freeze', 'Freeze'],
  pantry: ['DOP_Pantry', 'Pantry'],
};
function time(p, storage) {
  for (const c of COLUMNS[storage]) {
    if (p[`${c}_Min`] && DAYS[p[`${c}_Metric`]]) {
      const unit = p[`${c}_Metric`];
      const range = p[`${c}_Min`] === p[`${c}_Max`] ? `${p[`${c}_Min`]}` : `${p[`${c}_Min`]}–${p[`${c}_Max`]}`;
      return { days: p[`${c}_Min`] * DAYS[unit], text: `${range} ${unit.toLowerCase()}${c.endsWith('After_Opening') ? ' after opening' : ''}` };
    }
  }
  return null;
}

const out = [];
for (const [category, storage, old, ids, note] of ROWS) {
  const cited = ids.map((id) => ({ p: byId.get(id), t: time(byId.get(id), storage) })).filter((x) => x.t);
  const days = cited.length ? Math.min(...cited.map((x) => x.t.days)) : old;
  const refs = cited.map((x) => `#${x.p.ID} ${x.p.Name}${x.p.Name_subtitle ? ` (${x.p.Name_subtitle})` : ''}: ${x.t.text}`);
  const source = cited.length ? `USDA FoodKeeper v128 — shortest of ${cited.map((x) => `#${x.p.ID}`).join(', ')}` : `Frigo default — ${note}`;
  out.push({ category, storage, old, days, source, refs, note });
}

const sql = `-- Verified shelf-life table (generated by scripts/verify-shelf-life.mjs — do not edit by hand).
-- Source: ${fk._source}
-- Rule: the shortest FoodKeeper time among the products listed for each row (see docs/SHELF_LIFE.md).

insert into public.shelf_life (category, storage, days, source) values
${out.map((r) => `  ('${r.category}', '${r.storage}', ${r.days}, '${r.source.replace(/'/g, "''")}')`).join(',\n')}
on conflict (category, storage) do update set days = excluded.days, source = excluded.source;
`;
fs.writeFileSync(path.join(root, 'supabase/shelf-life-verified.sql'), sql);
// keep supabase/seed.sql (used for new databases) in step
const seedPath = path.join(root, 'supabase/seed.sql');
const seed = fs.readFileSync(seedPath, 'utf8');
const insert = sql.slice(sql.indexOf('insert into'));
fs.writeFileSync(seedPath, seed.replace(/(-- BEGIN shelf_life[^\n]*\n)[\s\S]*?(-- END shelf_life)/, `$1${insert}$2`));

const md = `# Shelf-life table — verified against USDA FoodKeeper

When an item has no date, Frigo estimates one from this table (category × storage place) and marks it "~".

**Source:** ${fk._source}

**Rule:** for each row we took the products most often found in a Moldovan fridge, looked up their official
FoodKeeper times, and used the **shortest minimum**: the safest choice, because a guessed date that is too long could
make someone eat spoiled food. The user can always change a date. Reproduce with \`npm run verify:shelf-life\`.

**ANSA Moldova:** we did not find a public household storage-time table from ANSA (ansa.gov.md) to compare with. *To check
by the team:* search ansa.gov.md and add any official Moldovan values here.

| Category | Storage | Before (starter) | Verified | FoodKeeper products used (ID: official time) |
|---|---|---|---|---|
${out.map((r) => `| ${r.category} | ${r.storage} | ${r.old} d | **${r.days} d** | ${r.refs.length ? r.refs.join('<br>') : r.note} |`).join('\n')}
`;
fs.writeFileSync(path.join(root, 'docs/SHELF_LIFE.md'), md);
const changed = out.filter((r) => r.old !== r.days);
console.log(`${out.length} rows, ${changed.length} changed:`);
console.table(changed.map((r) => ({ row: `${r.category}/${r.storage}`, before: r.old, verified: r.days })));
