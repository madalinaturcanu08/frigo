// Builds supabase/recipes.sql from content/recipes.json.
// Usage: node scripts/build-recipes-sql.mjs — then paste supabase/recipes.sql into the Supabase SQL Editor.
// The SQL is safe to run again: recipes are updated in place by slug and their ingredients are replaced.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const { recipes } = JSON.parse(fs.readFileSync(path.join(root, 'content/recipes.json'), 'utf8'));
const LANGS = ['ro', 'ru', 'en'];
const CATEGORIES = ['dairy', 'cheese', 'eggs', 'meat', 'fish', 'vegetables', 'fruit', 'bread', 'leftovers', 'sauces', 'drinks', 'other'];

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

for (const r of recipes) {
  if (!/^[a-z0-9-]+$/.test(r.slug)) throw new Error(`bad slug: ${r.slug}`);
  for (const l of LANGS) if (!r.title?.[l] || !r.steps?.[l]?.length) throw new Error(`${r.slug}: missing ${l}`);
  for (const i of r.ingredients) {
    if (!CATEGORIES.includes(i.category)) throw new Error(`${r.slug}: unknown category ${i.category}`);
    for (const l of LANGS) if (!i.label?.[l]) throw new Error(`${r.slug}: ingredient label missing ${l}`);
  }
}

const out = [
  '-- GENERATED by scripts/build-recipes-sql.mjs from content/recipes.json — edit the JSON, not this file.',
  '-- Run after migrations 0001–0003. Safe to run again.',
  'begin;',
  '',
];

for (const r of recipes) {
  const cols = ['slug', 'emoji', 'minutes', 'servings', 'title_ro', 'title_ru', 'title_en', 'steps_ro', 'steps_ru', 'steps_en', 'source_note'];
  const vals = [
    r.slug,
    r.emoji,
    r.minutes,
    r.servings,
    ...LANGS.map((l) => r.title[l]),
    ...LANGS.map((l) => r.steps[l].join('\n')),
    r.source ?? 'Frigo starter recipe (AI draft) — check before the competition',
  ];
  out.push(
    `insert into public.recipes (${cols.join(', ')})`,
    `values (${vals.map((v) => (typeof v === 'number' ? v : q(v))).join(', ')})`,
    `on conflict (slug) do update set ${cols
      .filter((c) => c !== 'slug')
      .map((c) => `${c} = excluded.${c}`)
      .join(', ')};`,
    `delete from public.recipe_ingredients where recipe_id = (select id from public.recipes where slug = ${q(r.slug)});`,
  );
  r.ingredients.forEach((i, pos) => {
    out.push(
      `insert into public.recipe_ingredients (recipe_id, position, category, keyword, optional, label_ro, label_ru, label_en)` +
        ` select id, ${pos}, ${q(i.category)}, ${q(i.keywords?.length ? i.keywords.join(',') : null)}, ${i.optional ? 'true' : 'false'},` +
        ` ${LANGS.map((l) => q(i.label[l])).join(', ')} from public.recipes where slug = ${q(r.slug)};`,
    );
  });
  out.push('');
}
out.push('commit;', '');

fs.writeFileSync(path.join(root, 'supabase/recipes.sql'), out.join('\n'));
console.log(`supabase/recipes.sql: ${recipes.length} recipes, ${recipes.reduce((n, r) => n + r.ingredients.length, 0)} ingredients`);
